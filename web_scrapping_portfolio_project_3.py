verification_df

import requests
from bs4 import BeautifulSoup
import pandas as pd

# 1. List to store books across all pages
all_books = []

# 2. Loop through the first 3 pages
for page in range(1, 4):
    # Construct the URL for each page
    page_url = f"http://books.toscrape.com/catalogue/page-{page}.html"

    # Send HTTP request
    response = requests.get(page_url)

    # Parse HTML
    soup = BeautifulSoup(response.text, "html.parser")
    book_elements = soup.find_all("article", class_="product_pod")

    # Extract details for each book on the current page
    for book in book_elements:
        title = book.h3.a["title"]
        raw_price = book.find("p", class_="price_color").text
        clean_price = float(raw_price.replace("Â", "").replace("£", "").strip())

        all_books.append({
            "title": title,
            "price_gbp": clean_price,
            "page_number": page
        })

# 3. Convert all extracted books into a single DataFrame
df_multi_page = pd.DataFrame(all_books)

# 4. Print total books collected and preview counts per page
print(f"Total books collected across 3 pages: {len(df_multi_page)}")
print("\nBooks collected per page:")
print(df_multi_page["page_number"].value_counts())

