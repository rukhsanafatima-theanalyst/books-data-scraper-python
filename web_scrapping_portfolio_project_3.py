import requests
from bs4 import BeautifulSoup

# 2. Define the webpage URL
url = "http://books.toscrape.com/"

# 3. Send a request to fetch the web page
response = requests.get(url)

# 4. Check if the website responded successfully (HTTP Status 200 means OK)
print("Status Code:", response.status_code)
print("Page downloaded successfully!")

# 1. Parse the downloaded HTML text using BeautifulSoup
soup = BeautifulSoup(response.text, "html.parser")

# 2. Find all book elements (each book is inside an <article class="product_pod"> tag)
book_elements = soup.find_all("article", class_="product_pod")

# 3. Print how many books were found on the page
print("Total books found on page 1:", len(book_elements))

# 1. Create an empty list to store the extracted book details
books_list = []

# 2. Loop through each of the 20 book elements
for book in book_elements:
    # Extract book title from the 'title' attribute inside the <a> tag
    title = book.h3.a["title"]

    # Extract raw price text (e.g., 'Â£51.77')
    raw_price = book.find("p", class_="price_color").text

    # Clean the price: remove 'Â' and '£' characters, then strip extra spaces
    clean_price_text = raw_price.replace("Â", "").replace("£", "").strip()

    # Convert cleaned text to a decimal number (float)
    clean_price = float(clean_price_text)

    # Append details as a dictionary
    books_list.append({
        "title": title,
        "price_gbp": clean_price
    })

# 3. Print the first 3 items to check the result
print("First 3 books extracted:")
print(books_list[:3])

import pandas as pd

# 1. Convert the list of book dictionaries into a DataFrame
df_books = pd.DataFrame(books_list)

# 2. Display the top 5 rows of the DataFrame
df_books.head()

import sqlite3

# 1. Connect to a SQLite database file (it creates the file if it doesn't exist)
conn = sqlite3.connect("scraped_data.db")

# 2. Save the DataFrame into a database table named 'scraped_books'
df_books.to_sql("scraped_books", conn, if_exists="replace", index=False)

# 3. Verify that the data was written correctly by querying the database back
verification_df = pd.read_sql_query("SELECT * FROM scraped_books LIMIT 5;", conn)

# 4. Close the database connection
conn.close()

